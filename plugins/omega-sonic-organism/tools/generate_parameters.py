"""Generate the C++ registry from the supplied permanent host contract."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
params = json.loads((root/'contracts/parameters.json').read_text(encoding='utf-8'))['parameters']
lines = ['// Generated by tools/generate_parameters.py. Edit the contract, not this file.', '#pragma once', '#include <array>', '#include <cmath>', '#include <cstdint>', 'namespace omega {', 'struct ParameterDefinition { uint32_t id; const char* key; const char16_t* title; const char16_t* unit; double minimum, maximum, initial; int steps; bool logarithmic, automatable; const char16_t* choices[4]; };', 'inline constexpr std::array<ParameterDefinition, 18> parameterDefinitions {{']
for p in params:
    steps = len(p.get('choices', []))-1 if p['kind']=='enumeration' else 0
    choices = ','.join('u"'+c+'"' for c in p.get('choices', []))
    lines.append('  {%d, "%s", u"%s", u"%s", %.17g, %.17g, %.17g, %d, %s, %s, {%s}},' % (p['id'], p['key'], p['label'], p.get('unit',''), p.get('min',0),p.get('max',steps),p['default_normalized'],steps,str(p.get('scale')=='log').lower(),str(p['automatable']).lower(),choices))
lines += ['}};', 'inline double physical(const ParameterDefinition& p, double n) noexcept { return p.logarithmic ? p.minimum * std::pow(p.maximum/p.minimum,n) : p.minimum+(p.maximum-p.minimum)*n; }', 'inline int parameterIndex(uint32_t id) noexcept { return id>=100 && id<=117 ? static_cast<int>(id-100) : -1; }', '} // namespace omega', '']
output = '\n'.join(lines)
target = root/'core/include/omega/Parameters.h'
if '--check' in __import__('sys').argv:
    assert target.read_text(encoding='utf-8') == output, 'Generated registry differs from contract'
else:
    target.write_text(output,encoding='utf-8')
print('Parameter registry matches 15 permanent IDs and 3 additive V4 controls.')
